function pack(kind: 'action'|'camera', recipes: [string,string,string][]): WritingSkill[] {
  return recipes.map(([id,name,instruction]) => ({
    id:`previs-${kind}-${id}`, name, description:instruction.split('。')[0]+'。',
    collection:kind==='action'?'白模预演 · 动作风格':'白模预演 · 镜头描述',
    source:'local', uses:[kind==='action'?'previs-action':'previs-camera'],
    instruction:`${base}\n\n本技能风格：${instruction}`, sources,
  }));
}
